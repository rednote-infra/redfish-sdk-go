// Command modelgen renders checked-in Python SDK contracts as Go DTOs.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type field struct {
	Name, Type, JSON string
	Aliases          []string
	Required         bool
	Sensitive        bool
}
type model struct {
	Name   string
	Fields []field
	Root   bool
}
type schema struct {
	Source, Commit string
	Models         []model
	Enums          map[string]map[string]string
}

func main() {
	data, err := os.ReadFile("../internal/modelgen/schema.json")
	must(err)
	var s schema
	must(json.Unmarshal(data, &s))
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by go generate from %s@%s; DO NOT EDIT.\npackage models\n\nimport (\"encoding/json\";\"fmt\")\n\n", s.Source, s.Commit)
	keys := make([]string, 0, len(s.Enums))
	for k := range s.Enums {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, name := range keys {
		fmt.Fprintf(&out, "// %s is a protocol enumeration; unknown response values remain readable.\ntype %s string\nconst (\n", name, name)
		members := make([]string, 0, len(s.Enums[name]))
		for k := range s.Enums[name] {
			members = append(members, k)
		}
		sort.Strings(members)
		for _, k := range members {
			fmt.Fprintf(&out, "%s%s %s = %q\n", name, k, name, s.Enums[name][k])
		}
		fmt.Fprintln(&out, ")")
	}
	for _, m := range s.Models {
		if m.Root {
			fmt.Fprintf(&out, "type %s %s\n", m.Name, m.Fields[0].Type)
			continue
		}
		fmt.Fprintf(&out, "// %s matches the Python SDK response contract.\ntype %s struct {\n", m.Name, m.Name)
		for _, f := range m.Fields {
			tag := f.JSON + ",omitempty"
			if f.Required {
				tag = f.JSON
			}
			if f.JSON == "-" {
				tag = "-"
			}
			aliases := ""
			if len(f.Aliases) > 0 {
				aliases = " redfish:" + fmt.Sprintf("%q", strings.Join(f.Aliases, ","))
			}
			fmt.Fprintf(&out, "%s %s `json:%q%s`\n", f.Name, f.Type, tag, aliases)
		}

		fmt.Fprintln(&out, "Extra map[string]json.RawMessage `json:\"-\"`\nNullFields map[string]bool `json:\"-\"`\n}")
		fmt.Fprintf(&out, "func (m *%s) UnmarshalJSON(data []byte) error { type plain %s; extra,err:=decodeExtra(data,(*plain)(m));m.Extra=extra;return err }\n", m.Name, m.Name)
		fmt.Fprintf(&out, "func (m %s) MarshalJSON() ([]byte,error) { type plain %s; return encodeExtra(plain(m),m.Extra) }\n", m.Name, m.Name)

		for _, field := range m.Fields {
			if field.Sensitive {
				fmt.Fprintf(&out, "func(m %s) Format(state fmt.State,verb rune){formatSensitiveModel(state,m)}\n", m.Name)
				break
			}
		}
		hasURI, hasID := false, false
		idType := ""
		for _, f := range m.Fields {
			if f.Name == "ODataID" {
				hasURI = true
			}
			if f.Name == "ID" {
				hasID = true
				idType = f.Type
			}
		}
		if hasURI {
			fmt.Fprintf(&out, "func(m %s) ResourceURI() string {if m.ODataID==nil{return \"\"};return *m.ODataID}\n", m.Name)
		}
		if hasID && idType == "string" {
			fmt.Fprintf(&out, "func(m %s) ResourceID() string { return m.ID }\n", m.Name)
		} else if hasID {
			fmt.Fprintf(&out, "func(m %s) ResourceID() string {if m.ID==nil{return \"\"};return string(*m.ID)}\n", m.Name)
		}
	}
	formatted, err := format.Source([]byte(out.String()))
	must(err)
	must(os.WriteFile("models_gen.go", formatted, 0644))
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}

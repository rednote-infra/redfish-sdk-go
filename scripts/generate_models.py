"""Generate Go models from the checked-in Python SDK contract snapshot.

Run with Python's standard library and gofmt; importing the Python SDK is not required.
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render_models(schema):
    """Render the schema without changing the public Go model contract."""
    lines = [
        f"// Code generated by go generate from {schema['source']}@{schema['commit']}; DO NOT EDIT.",
        "package models",
        'import ("encoding/json";"fmt")',
    ]
    for name, members in sorted(schema["enums"].items()):
        lines.extend(
            [
                f"// {name} is a protocol enumeration; unknown response values remain readable.",
                f"type {name} string",
                "const (",
            ]
        )
        for key, value in sorted(members.items()):
            lines.append(f"{name}{key} {name} = {json.dumps(value)}")
        lines.append(")")
    for model in schema["models"]:
        name = model["name"]
        fields = model["fields"]
        if model["root"]:
            lines.append(f"type {name} {fields[0]['type']}")
            continue
        lines.extend(
            [
                f"// {name} matches the Python SDK response contract.",
                f"type {name} struct {{",
            ]
        )
        for field in fields:
            tag = field["json"]
            if not field["required"] and tag != "-":
                tag += ",omitempty"
            aliases = ""
            if field["aliases"]:
                aliases = " redfish:" + json.dumps(",".join(field["aliases"]))
            lines.append(
                f"{field['name']} {field['type']} `json:{json.dumps(tag)}{aliases}`"
            )
        lines.extend(
            [
                'Extra map[string]json.RawMessage `json:"-"`',
                'NullFields map[string]bool `json:"-"`',
                "}",
                f"func (m *{name}) UnmarshalJSON(data []byte) error {{ type plain {name}; extra,err:=decodeExtra(data,(*plain)(m));m.Extra=extra;return err }}",
                f"func (m {name}) MarshalJSON() ([]byte,error) {{ type plain {name}; return encodeExtra(plain(m),m.Extra) }}",
            ]
        )
        if any(field["sensitive"] for field in fields):
            lines.append(
                f"func(m {name}) Format(state fmt.State,verb rune){{formatSensitiveModel(state,m)}}"
            )
        by_name = {field["name"]: field for field in fields}
        if "ODataID" in by_name:
            lines.append(
                f'func(m {name}) ResourceURI() string {{if m.ODataID==nil{{return ""}};return *m.ODataID}}'
            )
        if "ID" in by_name:
            if by_name["ID"]["type"] == "string":
                lines.append(f"func(m {name}) ResourceID() string {{ return m.ID }}")
            else:
                lines.append(
                    f'func(m {name}) ResourceID() string {{if m.ID==nil{{return ""}};return string(*m.ID)}}'
                )
    return "\n".join(lines) + "\n"


def generate(schema_path, output_path):
    """Generate and format the complete model file before writing it."""
    schema = json.loads(schema_path.read_text())
    result = subprocess.run(
        ["gofmt"],
        input=render_models(schema).encode(),
        capture_output=True,
        check=True,
    )
    output_path.write_bytes(result.stdout)


if __name__ == "__main__":
    generate(ROOT / "scripts/modelgen/schema.json", ROOT / "models/models_gen.go")
